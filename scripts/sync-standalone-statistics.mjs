import { readFileSync, writeFileSync } from 'node:fs'

const page = new URL('../standalone-redirect/index.html', import.meta.url)
const queue = readFileSync(new URL('../src/shared/pwa/statisticsQueue.js', import.meta.url), 'utf8')
  .replace(/^export /gm, '')
const client = readFileSync(new URL('../src/shared/pwa/statisticsClient.js', import.meta.url), 'utf8')
  .replace(/^import .*\r?\n/gm, '')
  .replace(/^export \{.*\}.*\r?\n/gm, '')
  .replace(/^export /gm, '')
const start = '// BEGIN SHARED STATISTICS (generated by scripts/sync-standalone-statistics.mjs)'
const end = '// END SHARED STATISTICS'
const source = readFileSync(page, 'utf8').replace(/\r\n/g, '\n')
const first = source.indexOf(start)
const last = source.indexOf(end, first)
if (first < 0 || last < 0) throw new Error('Missing embedded statistics markers')
const shared = 'const { createPwaAnalytics } = (() => {\n' +
  (queue + '\n' + client).replace(/\r\n/g, '\n').trim() +
  '\nreturn { createPwaAnalytics };\n})();'
const output = source.slice(0, first + start.length) + '\n' + shared + '\n      ' + source.slice(last)
if (process.argv.includes('--check')) {
  if (output !== source) throw new Error('Run node scripts/sync-standalone-statistics.mjs')
} else {
  writeFileSync(page, output, 'utf8')
}
